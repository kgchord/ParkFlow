#!/usr/bin/env python3
"""
Derived FEA geometry from the SNAPSHOT of the repo STEP files (models/repo_step_snapshot, copied 24 Oct 23:38 from cad/step/;
sha256 in models/repo_step_snapshot/SHA256SUMS.txt).  cad/step/ was being regenerated by the CAD owner while this FEA was
done, so every FEA input is frozen here.

  models/base_weldment_t12.step   snapshot weldment with the bottom 4 mm of the 16 mm base plate removed (12 mm plate,
                                  plate top stays at z = 16) for the thinning check of CALCS section 2.
"""
import os
import cadquery as cq
HERE = os.path.dirname(os.path.abspath(__file__))
M = os.path.join(HERE, "..", "models")
w = cq.importers.importStep(os.path.join(M, "repo_step_snapshot", "base_weldment.step"))
cutter = cq.Workplane("XY").box(400, 400, 4, centered=(True, True, False))
w12 = w.cut(cutter)
cq.exporters.export(w12, os.path.join(M, "base_weldment_t12.step"))
v = w12.val()
bb = v.BoundingBox()
print("t12 valid", v.isValid(), "solids", len(w12.solids().vals()), "zmin %.1f zmax %.1f V %.1f cm3" % (bb.zmin, bb.zmax, v.Volume() / 1000))
