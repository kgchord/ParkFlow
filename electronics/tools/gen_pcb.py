pcbnew.SaveBoard(PCB, b2)
print('saved', PCB, 'footprints', len(comps), 'nets', len(nets))
json.dump({r: [round(v, 2) if isinstance(v, float) else v for v in p] for r, p in placed.items()}, open(os.path.join(HERE, '_placement.json'), 'w'), indent=0)

