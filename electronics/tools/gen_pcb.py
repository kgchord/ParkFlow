ebb = chk.GetBoardEdgesBoundingBox()
print(f'self-check: {len(pin2net)} netlist pins, mismatches {bad}; outline {ToMM(ebb.GetWidth()):.1f} x {ToMM(ebb.GetHeight()):.1f} mm; '
      f'footprints {len([f for f in chk.GetFootprints() if not f.GetReference().startswith("H")])}, mounting holes {len([f for f in chk.GetFootprints() if f.GetReference().startswith("H")])}')
sys.exit(1 if bad else 0)
