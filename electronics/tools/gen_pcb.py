#!/usr/bin/env python3
"""Build electronics/kicad/lane_controller.kicad_pcb from the schematic netlist (KiCad 7 pcbnew Python API).

PLACEMENT ONLY. The board is NOT routed: every connection is a ratsnest line except the two GND copper pours.
Steps: read lane_controller.net -> load every footprint from /usr/share/kicad/footprints -> assign pad nets ->
place in zones (mains/24 V/motor power left, logic centre, connectors on the edges) -> outline 100x80 mm, 4x M3 holes,
antenna keep-out, GND pours -> write net classes into lane_controller.kicad_pro -> save.
Run: python3 gen_pcb.py   (needs `import pcbnew`, i.e. the KiCad 7 python module, and `kicad-cli` already run on the schematic)
"""
import os, re, sys, json, math, collections
import pcbnew
from pcbnew import FromMM, ToMM, VECTOR2I, wxPoint

HERE = os.path.dirname(os.path.abspath(__file__))
KDIR = os.path.normpath(os.path.join(HERE, '..', 'kicad'))
NET = os.path.join(KDIR, 'lane_controller.net')
SCH = os.path.join(KDIR, 'lane_controller.kicad_sch')
PCB = os.path.join(KDIR, 'lane_controller.kicad_pcb')
PRO = os.path.join(KDIR, 'lane_controller.kicad_pro')
FPDIR = '/usr/share/kicad/footprints'
W, H = 100.0, 80.0                 # board size, mm
OX, OY = 60.0, 40.0                # board origin on the KiCad sheet (A4 landscape = 297x210)
def P(x, y): return VECTOR2I(FromMM(OX + x), FromMM(OY + y))

# ------------------------------------------------------------------ read netlist
txt = open(NET).read()
comps = {}
for m in re.finditer(r'\(comp \(ref "([^"]+)"\)\s*\(value "([^"]*)"\)\s*\(footprint "([^"]*)"\).*?\(tstamps "([^"]+)"\)\)', txt, re.S):
    comps[m.group(1)] = dict(value=m.group(2), fp=m.group(3), uuid=m.group(4))
nets = collections.OrderedDict()
for blk in re.split(r'\(net \(code "\d+"\) \(name "', txt.split('\n  (nets', 1)[1])[1:]:
    name = blk.split('"', 1)[0]
    nets[name] = re.findall(r'\(node \(ref "([^"]+)"\) \(pin "([^"]+)"\)', blk)
pin2net = {}
for n, nodes in nets.items():
    for r, p in nodes:
        pin2net[(r, p)] = n
comps = {r: c for r, c in comps.items() if not r.startswith('#')}

# schematic symbol positions (for grouping passives with the IC they belong to)
sch = open(SCH).read()
spos = {}
for m in re.finditer(r'\(symbol \(lib_id "[^"]+"\) \(at ([-\d.]+) ([-\d.]+) \d+\).*?\(property "Reference" "([^"]+)"', sch, re.S):
    spos[m.group(3)] = (float(m.group(1)), float(m.group(2)))

def section(ref):
    x, y = spos[ref]
    if x < 250: return 1 if y < 125 else 2 if y < 215 else 3 if y < 330 else 8
    if x < 500: return 4 if y < 215 else 5 if y < 330 else 9
    return 6 if y < 222 else 7 if y < 400 else 10

# ------------------------------------------------------------------ board
board = pcbnew.BOARD()
board.SetCopperLayerCount(2)
tb = board.GetTitleBlock()
tb.SetTitle('ParkFlow Lane Controller (ESP32-S3) - Rev A - PLACEMENT ONLY, UNROUTED')
tb.SetCompany('ParkFlow - Vishwakarma Awards Stage 2'); tb.SetRevision('A'); tb.SetDate('2026-10-24')
tb.SetComment(0, 'Generated by electronics/tools/gen_pcb.py from lane_controller.net')
tb.SetComment(1, 'Routing, DRC clean-up and final review are the team job in KiCad')
netitems = {}
for n in nets:
    ni = pcbnew.NETINFO_ITEM(board, n); board.Add(ni); netitems[n] = ni

def seg(x1, y1, x2, y2, layer=pcbnew.Edge_Cuts, w=0.1):
    s = pcbnew.PCB_SHAPE(board); s.SetShape(pcbnew.SHAPE_T_SEGMENT); s.SetLayer(layer)
    s.SetStart(P(x1, y1)); s.SetEnd(P(x2, y2)); s.SetWidth(FromMM(w)); board.Add(s)
for a, b in [((0, 0), (W, 0)), ((W, 0), (W, H)), ((W, H), (0, H)), ((0, H), (0, 0))]:
    seg(a[0], a[1], b[0], b[1])

def load_fp(ref):
    c = comps[ref]; lib, name = c['fp'].split(':')
    m = pcbnew.FootprintLoad(os.path.join(FPDIR, lib + '.pretty'), name)
    assert m, c['fp']
    m.SetFPID(pcbnew.LIB_ID(lib, name))
    m.SetReference(ref); m.SetValue(c['value'])
    m.SetPath(pcbnew.KIID_PATH('/' + c['uuid']))
    m.Value().SetVisible(False)
    m.Reference().SetTextSize(pcbnew.VECTOR2I(FromMM(0.8), FromMM(0.8))); m.Reference().SetTextThickness(FromMM(0.12))
    for pad in m.Pads():
        n = pin2net.get((ref, pad.GetNumber()))
        if n: pad.SetNet(netitems[n])
    return m

# the WROOM module footprint ships the antenna keep-out as its courtyard (48 x 41 mm); replace it by the body outline
def shrink_module_courtyard(m):
    for g in list(m.GraphicalItems()):
        if g.GetLayer() == pcbnew.F_CrtYd: m.Remove(g)
    r = pcbnew.PCB_SHAPE(m); r.SetShape(pcbnew.SHAPE_T_RECT); r.SetLayer(pcbnew.F_CrtYd); r.SetWidth(FromMM(0.05))
    r.SetStart(VECTOR2I(FromMM(-9.35), FromMM(-13.05))); r.SetEnd(VECTOR2I(FromMM(9.35), FromMM(13.05))); m.Add(r)

fps = {r: load_fp(r) for r in comps}
for r, m in fps.items(): board.Add(m)

# ------------------------------------------------------------------ placement helpers
occ = {'F': [], 'B': []}     # occupied rectangles (x1,y1,x2,y2) in board mm
MARGIN = 0.6
def rect_of(m):
    bb = m.GetBoundingBox(False, False)
    return (ToMM(bb.GetX()) - OX, ToMM(bb.GetY()) - OY, ToMM(bb.GetRight()) - OX, ToMM(bb.GetBottom()) - OY)
def overlap(a, b, mg=MARGIN):
    return not (a[2] + mg <= b[0] or b[2] + mg <= a[0] or a[3] + mg <= b[1] or b[3] + mg <= a[1])
def tht(m): return any(p.GetAttribute() in (pcbnew.PAD_ATTRIB_PTH, pcbnew.PAD_ATTRIB_NPTH) for p in m.Pads())
def put(m, cx, cy, rot, side='F'):
    """place so that the bounding-box centre is at (cx,cy)"""
    if m.IsFlipped() != (side == 'B'):
        m.Flip(m.GetPosition(), True)
    m.SetOrientationDegrees(rot)
    m.SetPosition(P(0, 0))
    r = rect_of(m)
    dx, dy = cx - (r[0] + r[2]) / 2, cy - (r[1] + r[3]) / 2
    m.SetPosition(P(dx, dy))
    return rect_of(m)
def free(r, side, inside=True):
    if inside and (r[0] < 0.6 or r[1] < 0.6 or r[2] > W - 0.6 or r[3] > H - 0.6): return False
    sides = ['F', 'B'] if side == 'THT' else [side]
    return not any(overlap(r, o) for s_ in sides for o in occ[s_])
def mark(r, side, m=None):
    if side == 'THT' and m is not None:
        occ['F'].append(r)                              # full body on the top side
        for p in m.Pads():                              # only the pads (+ clearance) on the bottom side
            bb = p.GetBoundingBox(); occ['B'].append((ToMM(bb.GetX()) - OX - 0.2, ToMM(bb.GetY()) - OY - 0.2, ToMM(bb.GetRight()) - OX + 0.2, ToMM(bb.GetBottom()) - OY + 0.2))
        return
    for s_ in (['F', 'B'] if side == 'THT' else [side]): occ[s_].append(r)

placed = {}
def place_fixed(ref, cx, cy, rot, side='F', inside=True):
    m = fps[ref]; r = put(m, cx, cy, rot, side)
    if inside and not free(r, 'THT' if tht(m) else side): print('WARN fixed part overlaps/outside:', ref, [round(v, 1) for v in r])
    mark(r, 'THT' if tht(m) else side, m); placed[ref] = (cx, cy, rot, side)
def place_near(ref, cx, cy, rot=0, allow_back=False, rmax=60):
    m = fps[ref]; is_t = tht(m)
    for step in range(0, int(rmax / 0.5)):
        rad = step * 0.5
        npts = max(1, int(2 * math.pi * rad / 0.5))
        for k in range(npts):
            a = 2 * math.pi * k / npts
            x, y = cx + rad * math.cos(a), cy + rad * math.sin(a)
            for side in (['F', 'B'] if allow_back and not is_t else ['F']):
                for rt in ([rot, rot + 90] if not is_t else [rot]):
                    r = put(m, x, y, rt, side)
                    if free(r, 'THT' if is_t else side):
                        mark(r, 'THT' if is_t else side, m); placed[ref] = (x, y, rt, side); return True
    print('FAILED to place', ref); return False

# mounting holes (M3, 3.2 mm drill) and the antenna keep-out
holes = []
for i, (x, y) in enumerate([(3.5, 3.5), (W - 3.5, 3.5), (3.5, H - 3.5), (W - 3.5, H - 3.5)]):
    m = pcbnew.FootprintLoad(os.path.join(FPDIR, 'MountingHole.pretty'), 'MountingHole_3.2mm_M3')
    m.SetFPID(pcbnew.LIB_ID('MountingHole', 'MountingHole_3.2mm_M3'))
    m.SetReference(f'H{i+1}'); m.SetValue('M3'); m.Reference().SetVisible(False); m.Value().SetVisible(False)
    board.Add(m); m.SetPosition(P(x, y)); mark((x - 3.4, y - 3.4, x + 3.4, y + 3.4), 'THT')

# ------------------------------------------------------------------ anchors (bounding-box centre x,y in board mm, rotation)
# rotation convention: +y of the footprint (wire entry of the screw terminals, mating face of USB-C) points to the
# bottom edge at 0, right edge at 90, top edge at 180, left edge at 270.
FIXED = {
    # left edge: 24 V logic input, IBT-2 module logic header (the motor power path does not pass over this board)
    'J1': (6.9, 14.5, 270), 'J14': (5.2, 52.0, 0),
    # bottom edge: E-stop loop + K1 coil, field I/O (limits, beam, presence), PSU/UPS status
    'J4': (19.2, 73.2, 0), 'J5': (52.5, 73.2, 0), 'J6': (84.0, 73.2, 0),
    # right edge: USB-C, RS485 to the RFID reader, buzzer, P10 sign power
    'J7': (93.2, 27.5, 90), 'J13': (93.2, 42.5, 90), 'J8': (93.2, 55.5, 90),
    # headers inside the logic zone
    'J11': (43.5, 11.5, 0), 'J9': (79.5, 51.4, 0), 'J10': (66.5, 62.5, 0),
}
for ref, (x, y, r) in FIXED.items(): place_fixed(ref, x, y, r)
# U4: antenna end flush with the top edge; the library courtyard is the antenna keep-out (T shape), so occupy it as two rectangles
fps['U4'].SetOrientationDegrees(0); fps['U4'].SetPosition(P(62.0, 13.2)); placed['U4'] = (62.0, 13.2, 0, 'F')
mark((38.0, -8.0, 86.0, 6.8), 'THT'); mark((52.0, 6.8, 72.0, 26.8), 'THT')
# USB-C on the right edge: mating face outside; the footprint's 'PCB Edge' drawing line is 3.1 mm from its origin
m = fps['J12']; m.SetOrientationDegrees(90); m.SetPosition(P(W - 3.1, 13.5)); r = rect_of(m); mark(r, 'THT'); placed['J12'] = (W - 3.1, 13.5, 90, 'F')

# ------------------------------------------------------------------ main ICs / power parts, then bulk parts (explicit target centres)
MAIN = {
    # sections 1+2 (top-left): input protection and the 24 V -> 5 V buck
    'F1': (18, 6), 'Q1': (29, 6.5), 'F2': (30, 14), 'D2': (19.5, 15), 'C1': (29, 22.5),
    'U1': (14, 28.5), 'D3': (14.5, 35.5), 'L1': (30, 34.5),
    # section 6: hardware interlocks (74AHCT1G08 gates next to the J14 header) and the coil flyback diode
    'D16': (28, 68), 'U9': (20, 47), 'U10': (20, 53), 'U19': (20, 59),
    # section 4 (centre-top): watchdog and BOOT/RESET buttons left of the module
    'U5': (44, 19), 'SW1': (44, 25), 'SW2': (44, 31),
    # section 3 (top-right): 3.3 V buck + USB protection
    'U2': (78, 12), 'L2': (82, 20), 'U3': (89, 11), 'D4': (79, 27), 'D18': (79, 31),
    # section 5: RS485
    'U6': (82, 36), 'D7': (88, 37), 'JP1': (86, 42),
    # section 9: HUB12 level shifter, buzzer driver, bulk
    'U18': (66, 55), 'Q5': (88, 62), 'C21': (56, 63),
    # section 8: contactor driver
    'Q4': (32, 71),
}
for ref in sorted(MAIN, key=lambda r: tht(fps[r]), reverse=True):
    place_near(ref, *MAIN[ref], allow_back=False, rmax=25)

# opto-isolated inputs: place U11-U16 (+ their R/D/C) in a block, centre-bottom
opto_xy = [(52, 33), (66, 33), (52, 41), (66, 41), (52, 49), (66, 49), (52, 57)]
for ref, xy in zip(['U11', 'U12', 'U13', 'U14', 'U15', 'U16', 'U17'], opto_xy):
    place_near(ref, *xy, allow_back=True, rmax=30)

# ------------------------------------------------------------------ everything else: attach to nearest anchor of the same schematic section
ANCHOR_PREFIX = ('U', 'J', 'Q', 'L', 'SW', 'JP')
def is_anchor(r): return r.startswith(ANCHOR_PREFIX) or r in ('C1', 'C21', 'D3', 'D2')
rest = [r for r in comps if r not in placed]
anchors = [r for r in placed if r in comps]
def nearest_anchor(ref):
    sx, sy = spos[ref]
    cand = [a for a in anchors if section(a) == section(ref)] or anchors
    return min(cand, key=lambda a: (spos[a][0] - sx) ** 2 + (spos[a][1] - sy) ** 2)
order = sorted(rest, key=lambda r: ((spos[r][0] - spos[nearest_anchor(r)][0]) ** 2 + (spos[r][1] - spos[nearest_anchor(r)][1]) ** 2))
# bigger parts first so that small parts fill the gaps
order.sort(key=lambda r: -(rect_of(fps[r])[2] - rect_of(fps[r])[0]) * (rect_of(fps[r])[3] - rect_of(fps[r])[1]))
for ref in order:
    a = nearest_anchor(ref)
    ax, ay = placed[a][0], placed[a][1]
    small = ref[0] in 'RCDQ' and not tht(fps[ref])
    place_near(ref, ax, ay, 0, allow_back=small)

# ------------------------------------------------------------------ GND pours, antenna keep-out rule area
def zone(poly, layer, net=None, keepout=False):
    z = pcbnew.ZONE(board); z.SetLayer(layer)
    if keepout:
        z.SetIsRuleArea(True); z.SetDoNotAllowCopperPour(True); z.SetDoNotAllowTracks(True); z.SetDoNotAllowVias(True)
        z.SetDoNotAllowFootprints(False)
        ls = pcbnew.LSET(pcbnew.F_Cu); ls.addLayer(pcbnew.B_Cu); z.SetLayerSet(ls)
    else:
        z.SetNet(netitems[net]); z.SetMinThickness(FromMM(0.25)); z.SetThermalReliefGap(FromMM(0.3)); z.SetThermalReliefSpokeWidth(FromMM(0.5))
        z.SetPadConnection(pcbnew.ZONE_CONNECTION_THERMAL)
    ol = pcbnew.SHAPE_LINE_CHAIN()
    for x, y in poly: ol.Append(FromMM(OX + x), FromMM(OY + y))
    ol.SetClosed(True); z.AddPolygon(ol); board.Add(z); return z
box = [(0.3, 0.3), (W - 0.3, 0.3), (W - 0.3, H - 0.3), (0.3, H - 0.3)]
zone(box, pcbnew.F_Cu, '/GND'); zone(box, pcbnew.B_Cu, '/GND')
zone([(38.0, -0.5), (86.0, -0.5), (86.0, 6.7), (38.0, 6.7)], pcbnew.F_Cu, keepout=True)   # copper-free under the antenna
# ------------------------------------------------------------------ silkscreen notes
def text(s, x, y, size=1.2, layer=pcbnew.F_SilkS):
    t = pcbnew.PCB_TEXT(board); t.SetText(s); t.SetPosition(P(x, y)); t.SetLayer(layer)
    t.SetTextSize(VECTOR2I(FromMM(size), FromMM(size))); t.SetTextThickness(FromMM(0.15)); board.Add(t)
text('ParkFlow Lane Controller Rev A - PLACEMENT ONLY, UNROUTED', 62, 2.6, 0.9, pcbnew.F_Fab)
text('24 V / MOTOR POWER ZONE', 19, 1.6, 0.9, pcbnew.F_Fab)
text('LOGIC / ESP32-S3', 45, 8.0, 0.9, pcbnew.F_Fab)
text('FIELD CONNECTORS', 30, 67.4, 0.9, pcbnew.F_Fab)
text('antenna keep-out: no copper, no parts', 62, 5.2, 0.8, pcbnew.F_Fab)
# reference designators on the Fab layers for now (keeps silkscreen clean while the board is unrouted)
for fp in board.GetFootprints():
    r = fp.GetReference()
    if r.startswith('H'): continue
    bb = rect_of(fp) if r != 'U4' else (0, 0, 20, 26)
    fp.Reference().SetLayer(pcbnew.B_Fab if fp.IsFlipped() else pcbnew.F_Fab)
# SMD / module-pad GND connections solid instead of thermal relief (avoids starved-thermal errors on tiny pads)
for fp in board.GetFootprints():
    for pad in fp.Pads():
        if pad.GetNetname() == '/GND' and (pad.GetAttribute() == pcbnew.PAD_ATTRIB_SMD or fp.GetReference() == 'U4'):
            pad.SetZoneConnection(pcbnew.ZONE_CONNECTION_FULL)

pcbnew.SaveBoard(PCB, board)
# reload through the project (net classes below) and fill the GND pours; filling a board that is not attached to a project crashes pcbnew 7.0

# ------------------------------------------------------------------ net classes in the project file (KiCad 7 reads them from .kicad_pro)
def ipc2221_width_mm(i_a, dt_k=20.0, oz=1.0, external=True):
    k = 0.048 if external else 0.024
    area_mil2 = (i_a / (k * dt_k ** 0.44)) ** (1 / 0.725)
    return area_mil2 / (1.378 * oz) * 0.0254
NC = [  # name, track width mm, clearance mm, via dia, via drill, nets, design current A (target) for the IPC-2221 check
    ('Default',  0.25, 0.20, 0.8, 0.4, [], 0.3),
    # no motor current on this board: the IBT-2 module B+/B-/M+/M- screw terminals carry it (off-board)
    ('Power_24V', 1.0, 0.30, 1.0, 0.5, ['/VIN_RAW', '/VIN_F', '/+24V', '/+24V_FIELD', '/K1_COIL_LO', '/ESTOP_LOOP', '/U1_SW', '/BUZ_LO'], 1.7),
    ('Power_5V', 1.2, 0.20, 0.8, 0.4, ['/+5V', '/+5V_LOGIC', '/VBUS'], 3.6),
    ('Power_3V3', 0.5, 0.20, 0.8, 0.4, ['/+3V3'], 0.7),
    ('GND', 0.8, 0.20, 0.8, 0.4, ['/GND'], 2.5),
]
def netclass_json(n, w, c, vd, vh):
    return {"bus_width": 12, "clearance": c, "diff_pair_gap": 0.25, "diff_pair_via_gap": 0.25, "diff_pair_width": 0.2, "line_style": 0,
            "microvia_diameter": 0.3, "microvia_drill": 0.1, "name": n, "pcb_color": "rgba(0, 0, 0, 0.000)", "schematic_color": "rgba(0, 0, 0, 0.000)",
            "track_width": w, "via_diameter": vd, "via_drill": vh, "wire_width": 6}
pro = json.load(open(PRO))
pro['net_settings'] = {"classes": [netclass_json(n, w, c, vd, vh) for n, w, c, vd, vh, _, _ in NC],
                       "meta": {"version": 3}, "net_colors": None, "netclass_assignments": None,
                       "netclass_patterns": [{"netclass": n, "pattern": pat} for n, *_, nl, _i in NC for pat in nl]}
pro.setdefault('board', {}).setdefault('design_settings', {})['rules'] = {"min_clearance": 0.2, "min_copper_edge_clearance": 0.3, "min_hole_to_hole": 0.25,
    "min_through_hole_diameter": 0.2, "min_track_width": 0.2, "min_via_diameter": 0.5}
pro['meta'] = {"filename": "lane_controller.kicad_pro", "version": 1}
json.dump(pro, open(PRO, 'w'), indent=2)
print('net classes:', [(n, w, round(ipc2221_width_mm(i), 2)) for n, w, *_, i in NC])

# reload through the project and fill the GND pours
b2 = pcbnew.LoadBoard(PCB)
